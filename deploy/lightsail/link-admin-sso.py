#!/usr/bin/env python3
"""SSH-only setup: explicitly link a newly created Keycloak identity to an admin."""
import getpass
import json
import pathlib
import runpy
import sys
import urllib.error
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent
helpers = runpy.run_path(str(ROOT / "create-first-admin.py"), run_name="helpers")
mysql, sql_text = helpers["mysql"], helpers["sql_text"]
BASE = "http://127.0.0.1:8180/sso"


def request(path, method="GET", data=None, token=None, form=False):
    headers = {}
    if token:
        headers["Authorization"] = "Bearer " + token
    body = None
    if data is not None:
        body = (urllib.parse.urlencode(data) if form else json.dumps(data)).encode()
        headers["Content-Type"] = "application/x-www-form-urlencoded" if form else "application/json"
    req = urllib.request.Request(BASE + path, data=body, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            content = response.read()
            return (json.loads(content) if content else None), response.headers
    except urllib.error.HTTPError as error:
        raise RuntimeError(f"Keycloak returned HTTP {error.code}. No password or token is printed.") from None
    except urllib.error.URLError:
        raise RuntimeError("Cannot connect to the local Keycloak service.") from None


def main():
    # This file is generated by init-env.sh and is readable only by its owner.
    env = dict(line.split("=", 1) for line in (ROOT / ".env").read_text().splitlines()
               if line and not line.startswith("#"))
    issuer = "https://" + env["PUBLIC_HOST"] + "/sso/realms/portfolio"
    token_data, _ = request("/realms/master/protocol/openid-connect/token", "POST", {
        "grant_type": "password", "client_id": "admin-cli", "username": "kc-admin",
        "password": env["KC_BOOTSTRAP_ADMIN_PASSWORD"],
    }, form=True)
    token = token_data["access_token"]
    request("/admin/realms/portfolio", token=token)
    if sys.argv[1:] == ["--check"]:
        mysql("SELECT COUNT(*) FROM user_external_identities;")
        print("Keycloak admin access and service database connection verified. No changes made.")
        return
    if sys.argv[1:]:
        raise ValueError("Usage: python3 link-admin-sso.py [--check]")
    email = input("Existing service admin email: ").strip()
    user_id = mysql("SELECT id FROM users WHERE email=" + sql_text(email)
                    + " AND role=" + sql_text("관리자") + ";")
    if not user_id.isdigit():
        raise ValueError("No matching service admin found.")
    if mysql("SELECT COUNT(*) FROM user_external_identities WHERE user_id=" + user_id
             + " AND issuer=" + sql_text(issuer) + ";") != "0":
        raise ValueError("This admin already has an SSO link. Nothing changed.")
    query = urllib.parse.urlencode({"username": email, "exact": "true"})
    existing, _ = request("/admin/realms/portfolio/users?" + query, token=token)
    if existing:
        raise ValueError("Keycloak username already exists. Stop and review the existing identity; no automatic linking.")
    password = getpass.getpass("New SSO password (hidden, at least 12 characters): ")
    if len(password) < 12 or len(password.encode()) > 72:
        raise ValueError("Use at least 12 characters and at most 72 UTF-8 bytes.")
    if password != getpass.getpass("Confirm SSO password: "):
        raise ValueError("Passwords do not match.")
    # Disabled until the explicit issuer + subject link has been written.
    _, headers = request("/admin/realms/portfolio/users", "POST", {
        "username": email, "email": email, "enabled": False,
        "firstName": "Portfolio", "lastName": "Admin", "emailVerified": False,
        "credentials": [{"type": "password", "value": password, "temporary": False}],
    }, token=token)
    del password
    subject = headers["Location"].rstrip("/").rsplit("/", 1)[-1]
    user_path = "/admin/realms/portfolio/users/" + urllib.parse.quote(subject, safe="")
    try:
        mysql("INSERT INTO user_external_identities (user_id,issuer,subject) VALUES ("
              + user_id + "," + sql_text(issuer) + "," + sql_text(subject) + ");")
        request(user_path, "PUT", {"enabled": True}, token=token)
    except Exception:
        print("Setup did not finish. Do not enable the new identity manually; review its link first.", file=sys.stderr)
        raise
    print("SSO account created and linked. Log out, then choose Keycloak/SSO login.")
    print("Use the email and SSO password you entered. Your local-login password is unchanged.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, RuntimeError, KeyError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
    except (EOFError, KeyboardInterrupt):
        print("\nCancelled. If account creation had started, review its status before retrying.", file=sys.stderr)
        sys.exit(1)
